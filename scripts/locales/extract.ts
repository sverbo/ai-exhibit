/**
 * Keeps the translation catalogs in sync with the English sources:
 * presentations/canonical/locales/<lang>.json, one entry per slide text:
 *
 *   "02-tokens/visual.props.items.3": { "source": "<English>", "text": "<translation>" }
 *   "copy:Stop":                      { "source": "Stop", "text": "Arrêter" }
 *
 * Scene texts are keyed by scene and path; component copy (scene-components)
 * by its English text. New texts are added with an empty translation;
 * existing translations are never changed (verify:content reports those
 * whose English changed since); entries whose text is gone are kept and
 * reported, or removed with --prune. Also writes locales/index.ts.
 *
 *   pnpm locales:extract              every locale but English
 *   pnpm locales:extract --lang de    one locale (creates de.json)
 *   pnpm locales:extract --prune      drop stale entries
 *   pnpm locales:extract --from-inline  fill empty entries from translations
 *                                     still written inline in the sources
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { copyKey, LOCALES, parseLocale, presentationTexts, REFERENCE_LOCALE, type Catalog, type Locale } from "@ai-exhibit/presentation-core";
import { canonical } from "@ai-exhibit/canonical";
import { scanCopy } from "./scan.ts";

const root = new URL("../../", import.meta.url).pathname;
const dir = join(root, "presentations/canonical/locales");

const { values: args } = parseArgs({
  options: {
    lang: { type: "string", multiple: true },
    prune: { type: "boolean", default: false },
    "from-inline": { type: "boolean", default: false },
  },
});
const locales: Locale[] = (args.lang ?? LOCALES.filter((l) => l !== REFERENCE_LOCALE)).map((l) => {
  const known = parseLocale(l);
  if (!known || known === REFERENCE_LOCALE) throw new Error(`"${l}" is not a locale to translate into (LOCALES: ${LOCALES.join(", ")})`);
  return known;
});

/**
 * Every text to translate, in order: scenes first, then component copy. A
 * copy text whose translation is still inline is left there, except with
 * --from-inline (then `inline` carries it into the catalog).
 */
function catalogSources(locale: Locale): { key: string; source: string; inline?: string }[] {
  const out: { key: string; source: string; inline?: string }[] = presentationTexts(canonical).map((t) => ({
    key: t.key,
    source: t.value.en,
    inline: t.value[locale], // as written in the source, for --from-inline
  }));
  const seen = new Set<string>();
  for (const c of scanCopy(root)) {
    if (seen.has(c.en) || (c.inline[locale] !== undefined && !args["from-inline"])) continue;
    seen.add(c.en);
    out.push({ key: copyKey(c.en), source: c.en, inline: c.inline[locale] });
  }
  return out;
}

function writeIndex(): void {
  const files = readdirSync(dir).filter((f) => /^[a-z]{2,3}\.json$/.test(f)).sort();
  const names = files.map((f) => f.replace(".json", ""));
  const lines = [
    "// Generated by `pnpm locales:extract`: one catalog per translated language.",
    'import type { Catalog, Locale } from "@ai-exhibit/presentation-core";',
    ...names.map((n) => `import ${n} from "./${n}.json" with { type: "json" };`),
    "",
    `export const catalogs: Partial<Record<Locale, Catalog>> = { ${names.join(", ")} };`,
    "",
  ];
  writeFileSync(join(dir, "index.ts"), lines.join("\n"));
}

for (const locale of locales) {
  const file = join(dir, `${locale}.json`);
  const old: Catalog = existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as Catalog) : {};
  const next: Catalog = {};
  let added = 0;
  const sources = catalogSources(locale);
  const keys = new Set(sources.map((s) => s.key));
  for (const { key, source, inline } of sources) {
    const kept = old[key];
    if (kept && kept.text.trim()) next[key] = kept;
    else {
      next[key] = { source, text: args["from-inline"] && inline ? inline : (kept?.text ?? "") };
      if (!kept) added++;
    }
  }
  const stale = Object.keys(old).filter((k) => !keys.has(k));
  if (!args.prune) for (const k of stale) next[k] = old[k]!;
  writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`);
  const untranslated = Object.values(next).filter((e) => !e.text.trim()).length;
  console.log(
    `${locale}.json: ${Object.keys(next).length} entries, ${added} added, ${untranslated} to translate, ${stale.length} stale${args.prune && stale.length ? " (removed)" : ""}`,
  );
}
writeIndex();
